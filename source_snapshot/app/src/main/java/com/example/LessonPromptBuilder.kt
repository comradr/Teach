package com.example

object LessonPromptBuilder {

    fun buildLessonSystemPrompt(useSecondClass: Boolean): String {
        val noLatexRule = """
            НЕ используй LaTeX и математическую разметку.
            Запрещены:
            - $...$
            - $$...$$
            - \( ... \)
            - \[ ... \]
            - \text{}
            - \frac{}
            - \times
            - \div
            - \cdot
            - \boxed{}
            и другие LaTeX-команды.
            Все математические выражения записывай обычным текстом Unicode, пригодным для непосредственной печати ученику.
            Примеры:
            НЕПРАВИЛЬНО: ${'$'}13 + 9 = \text{___}${'$'}
            ПРАВИЛЬНО: 13 + 9 = ___
            НЕПРАВИЛЬНО: ${'$'}5 \times 4 = 20${'$'}
            ПРАВИЛЬНО: 5 × 4 = 20
            НЕПРАВИЛЬНО: ${'$'}20 \div 4 = 5${'$'}
            ПРАВИЛЬНО: 20 ÷ 4 = 5
            НЕПРАВИЛЬНО: \frac{3}{4}
            ПРАВИЛЬНО: 3/4
            Для пропуска ответа используй: ___
            Не используй математические dollar-delimiters даже внутри Markdown.
        """.trimIndent()

        return if (useSecondClass) {
            """
            Ты — опытный школьный методист для 1–5 классов, в том числе для малокомплектной школы.
            ДВА КЛАССА ОДНОВРЕМЕННО.
            Используй принцип «качелей»: пока учитель работает с одним классом, второй выполняет самостоятельную работу.
            Структура должна чётко разделять этапы урока.
            Обязательно составь единую временную таблицу формата:
            | Время | Действия учителя | Класс 1 | Класс 2 | Кто работает самостоятельно |
            Каждый этап указывай конкретным непрерывным интервалом времени, например 0–5, 5–12, 12–20 минут.
            Интервалы не должны пересекаться или оставлять необъяснённые разрывы и вместе должны покрывать всю длительность урока.
            Учитель физически не может одновременно объяснять новый материал обоим классам.
            Ни один непрерывный период самостоятельной работы класса не должен превышать заданный пользователем максимум.
            После каждого продолжительного самостоятельного блока предусматривай возвращение учителя к этому классу: проверку, обратную связь или новый инструктаж.
            Временная таблица должна учитывать темы каждого класса, ограничения самостоятельной работы и реальные переключения внимания учителя.
            Материалы и фотографии Класса 1 относятся только к Классу 1.
            Материалы Класса 2 относятся только к Классу 2.
            Не смешивай содержание изображений.
            В конце готовых материалов добавь `## Карточка — ученику` (сделай две отдельные карточки, если два класса) и затем `## Ответы учителю`. Обязательно используй именно этот заголовок `## Карточка — ученику`.
            Оформи план в формате Markdown.
            
            $noLatexRule
            """.trimIndent()
        } else {
            """
            Ты — опытный школьный методист для 1–5 классов.
            ФОРМАТ УРОКА: ОДИН КЛАСС.
            Существует только выбранный класс, нельзя добавлять второй класс, нельзя придумывать вторую группу, нельзя использовать схему совмещённого урока, нельзя строить расписание «качели».
            Структура урока: | Время | Этап урока | Действия учителя | Деятельность учеников | Материалы/заметки |.
            Все приложенные изображения относятся к единственному классу.
            В конце готовых материалов добавь `## Карточка — ученику` (полностью готовая карточка с заданиями для печати) и затем `## Ответы учителю`.
            Оформи план в формате Markdown.
            
            $noLatexRule
            """.trimIndent()
        }
    }

    fun buildLessonUserPrompt(
        useSecondClass: Boolean,
        classASubject: String,
        classAGrade: String,
        classATopic: String,
        classALimit: String,
        classBSubject: String,
        classBGrade: String,
        classBTopic: String,
        classBLimit: String,
        planMode: String,
        lessonType: String,
        lessonDuration: Int,
        additionalInstructions: String
    ): String {
        val modeDesc = if (planMode == "Официальный") {
            "Формальный официальный план (с целями, задачами, УУД, этапами, формулировками для документации, но без избыточности)."
        } else {
            "Рабочий план «Для себя» (практичный, минимум бюрократии, чётко что говорит/делает учитель и дети)."
        }
        
        var prompt = "Формат плана: $modeDesc\n"
        prompt += "Тип урока: $lessonType\n"
        prompt += "Длительность урока: $lessonDuration минут.\n\n"

        if (useSecondClass) {
            prompt += "Класс 1: $classAGrade, Предмет: $classASubject\nТема: $classATopic\n"
            if (classALimit.isNotBlank()) prompt += "Ограничение самостоятельной работы: $classALimit минут.\n\n"
            
            prompt += "Класс 2: $classBGrade, Предмет: $classBSubject\nТема: $classBTopic\n"
            if (classBLimit.isNotBlank()) prompt += "Ограничение самостоятельной работы: $classBLimit минут.\n"
        } else {
            prompt += "Класс: $classAGrade, Предмет: $classASubject\nТема: $classATopic\n"
            if (classAGrade == "5 класс") {
                prompt += "Важно: Это 5 класс, задания не должны быть чрезмерно детскими (соответствовать возрасту и уровню).\n"
            }
        }

        if (additionalInstructions.isNotBlank()) {
            prompt += "\nДополнительные пожелания от учителя:\n$additionalInstructions\n"
        }

        return prompt
    }

    fun looksLikeTwoClassPlan(planContent: String): Boolean {
        val regex = Regex("""(?i)(Класс\s*[1АA].*?Класс\s*[2БB]|Тема класса\s*1.*?Тема класса\s*2)""", RegexOption.DOT_MATCHES_ALL)
        return regex.containsMatchIn(planContent)
    }
}
